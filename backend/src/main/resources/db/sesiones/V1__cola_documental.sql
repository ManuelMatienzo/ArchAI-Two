CREATE TABLE IF NOT EXISTS operaciones_documentales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coleccion VARCHAR(80) NOT NULL,
    documento_id VARCHAR(240) NOT NULL,
    contenido TEXT NOT NULL,
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_outbox_documento ON operaciones_documentales(coleccion, documento_id);
